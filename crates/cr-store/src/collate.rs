//! The order of the originals' sorted list boxes and combo boxes: Windows
//! `CompareStringW` with `NORM_IGNORECASE` in the user's locale (en-US),
//! over the Windows-1252 text the programs keep.
//!
//! A string's sort key is built as Windows builds it: the primary weights
//! of its characters, then a diacritic weight and a case weight for each
//! of them (with trailing defaults dropped), and last the "word sort"
//! weights of hyphens, apostrophes and control characters, which only
//! break ties, each with how many primary weights come before it. Keys
//! compare byte by byte. The weights of every Windows-1252 character were
//! read with `LCMapStringW(LCMAP_SORTKEY | NORM_IGNORECASE)` under Wine,
//! and the comparison was checked against `CompareStringW` on 60,000
//! random pairs.

use std::cmp::Ordering;

use cr_formats::archive::ansi_bytes;

/// How a Windows-1252 character sorts.
#[derive(Clone, Copy)]
enum Weight {
    /// Not seen at all (NUL, the soft hyphen).
    N,
    /// Only breaks ties, with this weight (hyphens, apostrophes, controls).
    S(u8),
    /// Primary weights, each with its diacritic and case weight
    /// (ligatures such as Æ and ß have two).
    W(&'static [(u16, u8, u8)]),
}

