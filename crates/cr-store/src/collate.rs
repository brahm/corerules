/// The sort key of `s`.
pub fn sort_key(s: &str) -> Vec<u8> {
    let mut primary = Vec::new();
    let mut diacritic = Vec::new();
    let mut case = Vec::new();
    let mut special = Vec::new();
    for b in ansi_bytes(s) {
        match TABLE[usize::from(b)] {
            N => {}
            S(weight) => {
                let at = u16::MAX - (primary.len() / 2) as u16;
                special.extend_from_slice(&at.to_be_bytes());
                special.extend_from_slice(&[weight, 0x12]);
            }
            W(weights) => {
                for &(p, d, c) in weights {
                    primary.extend_from_slice(&p.to_be_bytes());
                    diacritic.push(d);
                    case.push(c);
                }
            }
        }
    }
    for v in [&mut diacritic, &mut case] {
        while v.last() == Some(&2) {
            v.pop();
        }
    }
    let mut key = primary;
    key.push(1);
    key.append(&mut diacritic);
    key.push(1);
    key.append(&mut case);
    key.extend_from_slice(&[1, 1]);
    key.append(&mut special);
    key.push(0);
    key
}

/// The order of two entries of a sorted list box.
pub fn list_cmp(a: &str, b: &str) -> Ordering {
    sort_key(a).cmp(&sort_key(b))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn keys_are_those_windows_makes() {
        // LCMapStringW(LCMAP_SORTKEY | NORM_IGNORECASE) under Wine.
        for (text, key) in [
            ("a", "0e020101010100"),
            ("co-op", "0e0a0e7c0e7c0e7e01010101fffd821200"),
            ("\u{c6}\u{e0}", "0e020e210e020102020f01010100"),
            ("a'b-c", "0e020e090e0a01010101fffe8012fffd821200"),
            ("\u{df}a-b", "0e910e910e020e0901010101fffc821200"),
            ("x\u{b2}a", "0ea60d1c0e0201010206010100"),
            ("a\u{ad}b", "0e020e090101010100"),
        ] {
            let hex: String = sort_key(text).iter().map(|b| format!("{b:02x}")).collect();
            assert_eq!(hex, key, "{text}");
        }
    }

    #[test]
    fn lists_sort_as_windows_does() {
        // CompareStringW(NORM_IGNORECASE) under Wine.
        let mut names = vec![
            "coop", "co-op", "Co-op", "b", "A", "\u{e0}", "a", "(x)", "1", "_a", "a b", "ab",
        ];
        names.sort_by(|a, b| list_cmp(a, b));
        assert_eq!(
            names,
            [
                "(x)", "_a", "1", "A", "a", "\u{e0}", "a b", "ab", "b", "coop", "co-op", "Co-op"
            ]
        );
    }
}
