//! The Markdown export, which the app offers in place of the Expansion's
//! RTF. It holds what the HTML export holds, in UTF-8 with `\n` line ends:
//! the character's name as the title, each box as a section, tables as
//! GitHub tables, lists nested as in the sheet, and the portrait as an
//! image when its file is in the installation.

use super::{Align, Block, CellKind, Flavor, ListItem, SectionContent, Sheet, Table};

impl Sheet {
    /// The Markdown export, with `date` in the footer as
    /// [`super::Timestamp::format`] gives it.
    pub fn to_markdown(&self, date: &str) -> String {
        let mut out = format!("# {}\n", escape_line(&self.title));
        for section in &self.sections {
            match &section.content {
                SectionContent::PageBreak => out.push_str("\n---\n"),
                SectionContent::Columns(columns) => {
                    for b in columns.iter().flatten() {
                        out.push_str(&format!("\n## {}\n", escape_line(&b.title)));
                        for block in &b.body {
                            self.block(&mut out, block);
                        }
                    }
                }
            }
        }
        let program = match self.flavor {
            Flavor::Expansion => "Advanced Dungeons & Dragons Core Rules 2.0 Expansion",
            Flavor::Core20 => "Advanced Dungeons & Dragons Core Rules CD-ROM 2.0",
        };
        out.push_str(&format!(
            "\n---\n\n*Generated by the {program} on {date}*\n"
        ));
        out
    }

    fn block(&self, out: &mut String, block: &Block) {
        match block {
            Block::Table(table) => table_to(out, table),
            Block::List(items) => {
                out.push('\n');
                list_to(out, items, 0);
            }
            Block::Paragraph(text) => {
                for line in text.lines().map(str::trim).filter(|l| !l.is_empty()) {
                    out.push('\n');
                    out.push_str(&escape_line(line));
                    out.push('\n');
                }
            }
            Block::Lines(lines) => {
                out.push('\n');
                let lines: Vec<String> = lines.iter().map(|l| escape_line(l)).collect();
                out.push_str(&lines.join("\\\n"));
                out.push('\n');
            }
            Block::Image { file, .. } => {
                if let Some(file) = file {
                    let url = file.display().to_string().replace(' ', "%20");
                    out.push_str(&format!("\n![{}](file://{url})\n", escape(&self.title)));
                }
            }
        }
    }
}

/// A GitHub table. Markdown tables need a heading row: a first row of
/// headings is used as it, otherwise the heading row is left empty. In a
/// table with headings, spanned cells are followed by empty cells so the
/// columns stay under their headings; the other tables only lay out
/// "Label: value" cells, and spans would add empty columns.
fn table_to(out: &mut String, table: &Table) {
    let spans = table
        .rows
        .iter()
        .flatten()
        .any(|c| c.kind == CellKind::Header);
    let span = |c: &super::Cell| if spans { c.colspan.max(1) as usize } else { 1 };
    let width = table
        .rows
        .iter()
        .map(|row| row.iter().map(span).sum())
        .max()
        .unwrap_or(0);
    if width == 0 || table.rows.is_empty() {
        return;
    }
    let row_cells = |row: &[super::Cell]| {
        let mut cells = Vec::new();
        let mut aligns = Vec::new();
        for cell in row {
            let text = escape(&cell.text.replace('\n', " "));
            let text = text.trim();
            cells.push(if cell.kind == CellKind::Large && !text.is_empty() {
                format!("**{text}**")
            } else {
                text.to_owned()
            });
            aligns.push(cell.align);
            for _ in 1..span(cell) {
                cells.push(String::new());
                aligns.push(cell.align);
            }
        }
        cells.resize(width, String::new());
        aligns.resize(width, Align::Left);
        (cells, aligns)
    };
    let headed = table.rows[0].iter().all(|c| c.kind == CellKind::Header);
    let (heading, aligns) = if headed {
        row_cells(&table.rows[0])
    } else {
        (vec![String::new(); width], row_cells(&table.rows[0]).1)
    };
    let line = |out: &mut String, cells: &[String]| {
        out.push('|');
        for cell in cells {
            out.push(' ');
            out.push_str(cell);
            out.push_str(" |");
        }
        out.push('\n');
    };
    out.push('\n');
    line(out, &heading);
    let rule: Vec<String> = aligns
        .iter()
        .map(|a| {
            match a {
                Align::Left => "---",
                Align::Center => ":---:",
                Align::Right => "---:",
            }
            .to_owned()
        })
        .collect();
    line(out, &rule);
    for row in &table.rows[usize::from(headed)..] {
        line(out, &row_cells(row).0);
    }
}

fn list_to(out: &mut String, items: &[ListItem], level: usize) {
    for item in items {
        out.push_str(&"  ".repeat(level));
        out.push_str("- ");
        out.push_str(&escape_line(item.text.replace('\n', " ").trim()));
        out.push('\n');
        if let Some(children) = &item.children {
            list_to(out, children, level + 1);
        }
    }
}

/// Escapes the characters Markdown would read as markup inside a line.
fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        if matches!(c, '\\' | '`' | '*' | '_' | '[' | ']' | '<' | '>' | '|') {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// [`escape`], and a line start that would begin a heading, a list, a
/// quote or a rule is escaped too.
fn escape_line(text: &str) -> String {
    let text = escape(text);
    if text.starts_with(['#', '-', '+', '=']) {
        return format!("\\{text}");
    }
    let digits = text.chars().take_while(char::is_ascii_digit).count();
    if digits > 0 && text[digits..].starts_with(['.', ')']) {
        return format!("{}\\{}", &text[..digits], &text[digits..]);
    }
    text
}

#[cfg(test)]
mod tests {
    use super::super::{Cell, Section, SheetBox};
    use super::*;

    fn sheet(body: Vec<Block>) -> Sheet {
        Sheet {
            title: "Borin *the* Bold".into(),
            flavor: Flavor::Expansion,
            sections: vec![
                Section {
                    id: 0,
                    content: SectionContent::Columns(vec![vec![SheetBox {
                        title: "Combat".into(),
                        body,
                    }]]),
                },
                Section {
                    id: 19,
                    content: SectionContent::PageBreak,
                },
            ],
            border: None,
        }
    }

    #[test]
    fn writes_boxes_tables_lists_and_the_footer() {
        let table = Table {
            columns: 3,
            rows: vec![
                vec![Cell::header("Weapon"), Cell::header("Speed").right()],
                vec![Cell::new("Bo stick"), Cell::new("3").right()],
                vec![Cell::new("Note | wide").span(2)],
            ],
        };
        let list = vec![ListItem {
            text: "Backpack".into(),
            children: Some(vec![ListItem {
                text: "* Gold Pieces x116".into(),
                children: None,
            }]),
        }];
        let text = sheet(vec![
            Block::Table(table),
            Block::List(list),
            Block::Paragraph("1. First\n\n\t-3 to hit".into()),
            Block::Lines(vec!["Long sword".into(), "Bow".into()]),
        ])
        .to_markdown("10/19/2026 03:05 PM");
        assert_eq!(
            text,
            "# Borin \\*the\\* Bold\n\
             \n## Combat\n\
             \n| Weapon | Speed |\n\
             | --- | ---: |\n\
             | Bo stick | 3 |\n\
             | Note \\| wide |  |\n\
             \n- Backpack\n  - \\* Gold Pieces x116\n\
             \n1\\. First\n\
             \n\\-3 to hit\n\
             \nLong sword\\\nBow\n\
             \n---\n\
             \n---\n\n*Generated by the Advanced Dungeons & Dragons Core Rules 2.0 \
             Expansion on 10/19/2026 03:05 PM*\n"
        );
    }

    #[test]
    fn a_table_without_headings_gets_an_empty_heading_row() {
        let table = Table {
            columns: 2,
            rows: vec![
                vec![Cell::large("Str:"), Cell::large("9").center()],
                vec![Cell::new("Weight Allowance: 35 lbs").span(2)],
            ],
        };
        let text = sheet(vec![Block::Table(table)]).to_markdown("");
        assert!(text.contains(
            "\n|  |  |\n| --- | :---: |\n| **Str:** | **9** |\n| Weight Allowance: 35 lbs |  |\n"
        ));
    }
}
