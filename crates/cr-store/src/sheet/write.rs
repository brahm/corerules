//! The TXT and HTML exports, written exactly as the originals' writers
//! write them (Expansion: TXT 0x6727d0, HTML 0x676360; Core Rules 2.0:
//! HTML only). Lines end in CRLF, because the originals open the file in
//! text mode.

use super::{Align, Block, CellKind, Flavor, ListItem, Section, SectionContent, Sheet, Table};

/// Width of the TXT rules (the writer's +0x24).
const TXT_WIDTH: usize = 80;

/// The moment an export is made, as the footer (and the HTML header)
/// shows it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Timestamp {
    pub year: u32,
    pub month: u32,
    pub day: u32,
    pub hour: u32,
    pub minute: u32,
    pub second: u32,
}

impl Timestamp {
    /// The current time in UTC (the originals use local time).
    pub fn now_utc() -> Self {
        let secs = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_secs());
        let days = (secs / 86_400) as i64;
        let rem = secs % 86_400;
        // Days to civil date (Howard Hinnant's algorithm).
        let z = days + 719_468;
        let era = z.div_euclid(146_097);
        let doe = z - era * 146_097;
        let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
        let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
        let mp = (5 * doy + 2) / 153;
        let day = (doy - (153 * mp + 2) / 5 + 1) as u32;
        let month = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
        let year = (yoe + era * 400 + i64::from(month <= 2)) as u32;
        Self {
            year,
            month,
            day,
            hour: (rem / 3600) as u32,
            minute: (rem / 60 % 60) as u32,
            second: (rem % 60) as u32,
        }
    }

    /// `%m/%d/%Y %I:%M %p` (Expansion) or `%m/%d/%y %H:%M:%S` (2.0).
    pub fn format(&self, flavor: Flavor) -> String {
        match flavor {
            Flavor::Expansion => {
                let hour12 = match self.hour % 12 {
                    0 => 12,
                    h => h,
                };
                let ampm = if self.hour < 12 { "AM" } else { "PM" };
                format!(
                    "{:02}/{:02}/{:04} {hour12:02}:{:02} {ampm}",
                    self.month, self.day, self.year, self.minute
                )
            }
            Flavor::Core20 => format!(
                "{:02}/{:02}/{:02} {:02}:{:02}:{:02}",
                self.month,
                self.day,
                self.year % 100,
                self.hour,
                self.minute,
                self.second
            ),
        }
    }
}

/// Writes `\n` as CRLF, as a text-mode `fopen` does.
fn crlf(text: String) -> String {
    text.replace('\n', "\r\n")
}

impl Sheet {
    /// The TXT export (Expansion only), with `date` in the footer as
    /// [`Timestamp::format`] gives it. Paragraphs and images write nothing
    /// in TXT, so ability descriptions, kit text and history are empty
    /// boxes, as in the original.
    pub fn to_txt(&self, date: &str) -> String {
        let mut out = String::new();
        out.push_str(&self.title);
        out.push_str("\n\n");
        for section in &self.sections {
            match &section.content {
                SectionContent::PageBreak => {
                    out.push_str("\n\n");
                    out.push_str(&"=".repeat(TXT_WIDTH));
                    out.push_str("\n\n");
                }
                SectionContent::Columns(columns) => {
                    for b in columns.iter().flatten() {
                        out.push_str(&"-".repeat(TXT_WIDTH));
                        out.push('\n');
                        out.push_str(&b.title);
                        out.push_str("\n\n");
                        for block in &b.body {
                            match block {
                                Block::Table(table) => {
                                    for row in &table.rows {
                                        for cell in row {
                                            out.push_str(&cell.text);
                                            out.push_str("; ");
                                        }
                                        out.push('\n');
                                    }
                                }
                                Block::List(items) => txt_list(&mut out, items, 1),
                                Block::Paragraph(_) | Block::Lines(_) | Block::Image(_) => {}
                            }
                        }
                    }
                }
            }
        }
        out.push_str("\n\n");
        out.push_str(&"=".repeat(TXT_WIDTH));
        out.push_str("Generated by the Advanced Dungeons & Dragons Core Rules 2.0 Expansion on ");
        out.push_str(date);
        out.push('\n');
        crlf(out)
    }

    /// The HTML export in the layout of the program the sheet was made
    /// for, with `date` in the header comment and footer as
    /// [`Timestamp::format`] gives it.
    pub fn to_html(&self, date: &str) -> String {
        let mut w = Html {
            out: String::new(),
            depth: 0,
            flavor: self.flavor,
        };
        w.document(self, date);
        crlf(w.out)
    }
}

fn txt_list(out: &mut String, items: &[ListItem], level: usize) {
    for item in items {
        out.push_str(&"  ".repeat(level));
        out.push_str(&item.text);
        out.push('\n');
        if let Some(children) = &item.children {
            txt_list(out, children, level + 1);
        }
    }
}

/// The HTML escape of the originals (0x6770a8): `>` and `<` become `&gt;`
/// and `&lt;`, then every `&` becomes `and`, the new ones included.
pub fn escape_html(text: &str) -> String {
    text.replace('>', "&gt;")
        .replace('<', "&lt;")
        .replace('&', "and")
}

struct Html {
    out: String,
    /// Nesting depth (writer +0x20), which sets the indentation.
    depth: usize,
    flavor: Flavor,
}

impl Html {
    fn expansion(&self) -> bool {
        self.flavor == Flavor::Expansion
    }

    fn indent(&mut self, n: usize) {
        self.out.push_str(&" ".repeat(n));
    }

    /// An opening tag: indented by depth + 2, then one level deeper.
    fn begin(&mut self, tag: &str, newline: bool) {
        self.indent(self.depth + 2);
        self.out.push_str(tag);
        if newline {
            self.out.push('\n');
        }
        self.depth += 1;
    }

    /// A closing tag: one level up, then indented by depth + 1.
    fn end(&mut self, tag: &str) {
        self.depth -= 1;
        self.indent(self.depth + 1);
        self.out.push_str(tag);
        self.out.push('\n');
    }

    fn document(&mut self, sheet: &Sheet, date: &str) {
        let (program, body) = if self.expansion() {
            ("Core Rules 2 Expansion", "<BODY BGCOLOR=\"#77BB77\">")
        } else {
            ("Core Rules CD-ROM 2.0", "<BODY BGCOLOR=77BB77>")
        };
        self.out.push_str(&format!(
            "<!DOCTYPE HTML PUBLIC \"-//W3C//DTD HTML 3.2//EN\"><!--\n  Generated by the \
             Advanced Dungeons & Dragons {program} on {date}\n-->\n <HTML>\n  <HEAD>\n    \
             <TITLE>{}</TITLE>\n  </HEAD>\n\n\n{body}\n",
            escape_html(&sheet.title)
        ));
        for section in &sheet.sections {
            match &section.content {
                SectionContent::PageBreak => self.out.push_str("<HR>"),
                SectionContent::Columns(columns) => self.section(section, columns),
            }
        }
        let link = if self.expansion() {
            "Advanced Dungeons & Dragons Core Rules 2.0 Expansion"
        } else {
            "Advanced Dungeons & Dragons Core Rules CD-ROM 2.0"
        };
        self.out.push_str(&format!(
            "<P>\nGenerated by the <A HREF=\"http://www.evermore88.com/html/core_rules_ii.html\">\
             {link}</A> on {date}\n</BODY>\n</HTML>\n\n\n\n"
        ));
    }

    fn section(&mut self, _section: &Section, columns: &[Vec<super::SheetBox>]) {
        let (row, col, sheet_box) = if self.expansion() {
            (
                "<TABLE BORDER=\"0\" WIDTH=\"100%\"><TR>",
                "<TD VALIGN=\"TOP\">",
                "<TABLE BORDER=\"1\" CELLPADDING=\"5\" WIDTH=\"100%\" BORDERCOLOR=\"#000000\" \
                 BORDERCOLORLIGHT=\"#000000\" BORDERCOLORDARK=\"#000000\"><TR><TD \
                 BGCOLOR=\"#F0F0F0\"><FONT FACE=\"Verdana,Arial\" SIZE=\"+1\"><STRONG>",
            )
        } else {
            (
                "<TABLE BORDER=0 WIDTH=100%%><TR>",
                "<TD VALIGN=TOP>",
                "<TABLE BORDER=1 CELLPADDING=5 WIDTH=100%% BORDERCOLOR=000000 \
                 BORDERCOLORLIGHT=000000 BORDERCOLORDARK=000000><TR><TD BGCOLOR=FFF0F0><FONT \
                 FACE=\"Verdana,Arial\" SIZE=+1><STRONG>",
            )
        };
        self.begin(row, true);
        for column in columns {
            self.begin(col, true);
            for b in column {
                self.begin(sheet_box, false);
                self.out.push_str(&escape_html(&b.title));
                self.out.push_str("</STRONG></FONT><BR>");
                for block in &b.body {
                    self.block(block);
                }
                self.end("</TD></TR></TABLE>");
            }
            self.end("</TD>");
        }
        self.end("</TR></TABLE>");
    }

    fn block(&mut self, block: &Block) {
        match block {
            Block::Table(table) => self.table(table),
            Block::List(items) => {
                self.list(items);
            }
            Block::Paragraph(text) => {
                let text = escape_html(text)
                    .replace('\t', "&nbsp;&nbsp;&nbsp;&nbsp;")
                    .replace('\n', "<BR>\n");
                self.out.push_str(&text);
                self.out.push_str("<BR>");
            }
            Block::Lines(lines) => {
                for line in lines {
                    self.out.push_str(&escape_html(line));
                    self.out.push_str("<BR>");
                }
            }
            Block::Image(path) => {
                self.out.push_str("<p><img src=\"file://");
                self.out.push_str(path);
                self.out.push_str("\" border=\"2\"></p>\n");
            }
        }
    }

    fn table(&mut self, table: &Table) {
        let open = if self.expansion() {
            "<TABLE WIDTH=\"100%\">"
        } else {
            "<TABLE WIDTH=100%%>"
        };
        self.begin(open, true);
        for row in &table.rows {
            self.indent(self.depth + 2);
            self.out.push_str("<TR>\n");
            for cell in row {
                self.indent(21);
                let tag = if cell.kind == CellKind::Header {
                    "TH"
                } else {
                    "TD"
                };
                self.out.push('<');
                self.out.push_str(tag);
                let align = match cell.align {
                    Align::Left => "LEFT",
                    Align::Center => "CENTER",
                    Align::Right => "RIGHT",
                };
                if self.expansion() {
                    if cell.colspan > 1 {
                        self.out.push_str(&format!(" COLSPAN=\"{}\"", cell.colspan));
                    }
                    self.out.push_str(&format!(" ALIGN=\"{align}\">"));
                } else {
                    if cell.colspan > 1 {
                        self.out.push_str(&format!(" COLSPAN={}", cell.colspan));
                    }
                    if cell.align != Align::Left {
                        self.out.push_str(&format!(" ALIGN={align}"));
                    }
                    self.out.push('>');
                }
                // Cells are written as they are (the export has "Detect
                // Snares & Pits" in a table).
                let text = &cell.text;
                if cell.kind == CellKind::Large {
                    let size = if self.expansion() {
                        "<FONT SIZE=\"+2\">"
                    } else {
                        "<FONT SIZE=+2>"
                    };
                    self.out.push_str(size);
                    self.out.push_str(text);
                    self.out.push_str("</FONT>");
                } else {
                    self.out.push_str(text);
                }
                self.out.push_str("</");
                self.out.push_str(tag);
                self.out.push_str(">\n");
            }
            self.indent(self.depth + 1);
            self.out.push_str("</TR>\n");
        }
        self.end("</TABLE>");
    }

    fn list(&mut self, items: &[ListItem]) {
        self.depth += 1;
        self.indent(self.depth + 2);
        self.out.push_str("<UL>\n");
        for item in items {
            self.indent(self.depth + 3);
            self.out.push_str("<LI>");
            self.out.push_str(&escape_html(&item.text));
            self.out.push('\n');
            if let Some(children) = &item.children {
                self.list(children);
            }
        }
        self.indent(self.depth + 1);
        self.out.push_str("</UL>\n");
        self.depth -= 1;
    }
}
